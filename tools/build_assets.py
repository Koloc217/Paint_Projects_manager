#!/usr/bin/env python3
"""Builds the front-end files that used to come from CDNs, so the app works without internet.

    python tools/build_assets.py           # everything: fonts, Chart.js, Tailwind CSS
    python tools/build_assets.py css       # only Tailwind CSS (after adding new classes to templates or JS)

Needs Node.js with npm (only on the machine where you build; the Pi just serves the result). The packages are
installed into a temporary folder, the project gets plain files:

    static/vendor/tailwind.css       Tailwind CSS built from the classes used in templates/ and static/*.js
    static/vendor/chart.umd.min.js   Chart.js
    static/fonts/fonts.css + *.woff2 theme fonts (Latin and Cyrillic), see FONTS below

Tailwind only keeps the classes it finds in the files, so a class written in a new template or script appears
in the page only after `python tools/build_assets.py css`. Classes must be written in full (`bg-red-500`), not glued
from parts (`bg-${color}-500`): the scanner does not run the code.
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VENDOR = os.path.join(ROOT, "static", "vendor")
FONTS_DIR = os.path.join(ROOT, "static", "fonts")

TAILWIND = "tailwindcss@3.4.19"
CHARTJS = "chart.js@4.5.1"
FONTSOURCE_VERSION = "5.2.5"
# Fontsource package -> weights. The same set the page used to load from Google Fonts.
FONTS = {
    "alegreya": (400, 500, 700),
    "chakra-petch": (500, 700),
    "jetbrains-mono": (400, 600, 700),
    "jura": (500, 700),
    "orbitron": (600, 800),
    "oswald": (500, 700),
    "pt-mono": (400,),
    "philosopher": (400, 700),
    "playfair-display-sc": (400, 700),
    "russo-one": (400,),
}
SUBSETS = ("latin", "latin-ext", "cyrillic", "cyrillic-ext")

TAILWIND_CONFIG = """module.exports = {
  darkMode: 'class',
  content: [%s],
  theme: { extend: { colors: { slate: { 850: '#151e2e' } } } },
};
"""


def run(cmd, cwd):
    print("$", " ".join(cmd))
    # npm is npm.cmd on Windows: shell=True lets the system find it
    subprocess.run(cmd if os.name != "nt" else " ".join(cmd), cwd=cwd, check=True, shell=(os.name == "nt"))


def npm_install(work, packages):
    run(["npm", "init", "-y", "--silent"], work)
    run(["npm", "install", "--silent", "--no-audit", "--no-fund", *packages], work)


def build_css(work):
    os.makedirs(VENDOR, exist_ok=True)
    globs = [os.path.join(ROOT, "templates", "**", "*.html"), os.path.join(ROOT, "static", "*.js"),
             os.path.join(ROOT, "static", "*.html")]
    config = os.path.join(work, "tailwind.config.js")
    with open(config, "w", encoding="utf-8") as f:
        f.write(TAILWIND_CONFIG % ", ".join(repr(g.replace("\\", "/")) for g in globs))
    src = os.path.join(work, "in.css")
    with open(src, "w", encoding="utf-8") as f:
        f.write("@tailwind base;\n@tailwind components;\n@tailwind utilities;\n")
    out = os.path.join(VENDOR, "tailwind.css")
    run([os.path.join(work, "node_modules", ".bin", "tailwindcss" + (".cmd" if os.name == "nt" else "")),
         "-c", config, "-i", src, "-o", out, "--minify"], work)
    print(f"  {os.path.relpath(out, ROOT)}: {os.path.getsize(out) // 1024} KB")


def build_chartjs(work):
    os.makedirs(VENDOR, exist_ok=True)
    src = os.path.join(work, "node_modules", "chart.js", "dist", "chart.umd.min.js")
    shutil.copyfile(src, os.path.join(VENDOR, "chart.umd.min.js"))
    print(f"  static/vendor/chart.umd.min.js: {os.path.getsize(src) // 1024} KB")


FACE_RE = re.compile(r"/\* ([a-z0-9-]+) \*/\s*(@font-face\s*\{.*?\})", re.S)


def build_fonts(work):
    if os.path.isdir(FONTS_DIR):
        shutil.rmtree(FONTS_DIR)
    os.makedirs(FONTS_DIR)
    css = ["/* Theme fonts (Fontsource, SIL Open Font License). Generated by tools/build_assets.py, do not edit.",
           "   A browser downloads a file only when the page really uses that font and those characters. */", ""]
    total = 0
    for pkg, weights in FONTS.items():
        base = os.path.join(work, "node_modules", "@fontsource", pkg)
        for weight in weights:
            with open(os.path.join(base, f"{weight}.css"), encoding="utf-8") as f:
                text = f.read()
            for name, face in FACE_RE.findall(text):
                if not any(name == f"{pkg}-{s}-{weight}-normal" for s in SUBSETS):
                    continue                                   # Greek, Vietnamese, Thai...: not needed
                file = f"{name}.woff2"
                shutil.copyfile(os.path.join(base, "files", file), os.path.join(FONTS_DIR, file))
                total += os.path.getsize(os.path.join(FONTS_DIR, file))
                face = re.sub(r"src:[^;]*;", f"src: url(./{file}) format('woff2');", face)
                css += [f"/* {name} */", face, ""]
    with open(os.path.join(FONTS_DIR, "fonts.css"), "w", encoding="utf-8") as f:
        f.write("\n".join(css))
    print(f"  static/fonts/: {len(os.listdir(FONTS_DIR)) - 1} files, {total // 1024} KB")


def main():
    only_css = sys.argv[1:] == ["css"]
    if sys.argv[1:] not in ([], ["css"]):
        print(__doc__)
        return 1
    if not shutil.which("npm"):
        print("npm not found: install Node.js (https://nodejs.org) on the machine where you build.")
        return 1
    work = tempfile.mkdtemp(prefix="ph-assets-")
    try:
        packages = [TAILWIND] if only_css else [TAILWIND, CHARTJS, *(f"@fontsource/{p}@{FONTSOURCE_VERSION}" for p in FONTS)]
        npm_install(work, packages)
        if not only_css:
            build_fonts(work)
            build_chartjs(work)
        build_css(work)
    finally:
        shutil.rmtree(work, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
